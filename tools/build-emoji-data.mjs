#!/usr/bin/env node
/*
 * Builds the emoji data behind the Link Up and Common Thread drills.
 *
 *   npm install            (pulls emojibase-data, MIT licensed)
 *   npm run build:emoji
 *
 * Reads emojibase-data's English dataset and data/emoji/tags.txt, then:
 *   1. checks every hand-tagged emoji exists, is a single base emoji (no skin
 *      tones) and is Emoji 13.0 or older, so it renders on nearly every phone;
 *   2. checks every connection has enough unambiguous members to be used;
 *   3. writes data/emoji/emoji-tagged.json: every emoji up to 13.0 with its
 *      emojibase name, group and keywords, plus our tags split into nouns,
 *      adjectives, descriptors and wordplay;
 *   4. rewrites the EMOJI-TAGS block in index.html with the compact tag table
 *      the drills read at runtime.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MAX_VERSION = 13.1;
const require = createRequire(import.meta.url);
const base = process.argv[2] || dirname(require.resolve('emojibase-data/package.json'));
const data = JSON.parse(readFileSync(join(base, 'en/data.json'), 'utf8'));
const messages = JSON.parse(readFileSync(join(base, 'en/messages.json'), 'utf8'));
const groupName = Object.fromEntries(messages.groups.map(g => [g.order, g.message]));
const subgroupName = Object.fromEntries(messages.subgroups.map(g => [g.order, g.message]));

const strip = s => s.replace(/️/g, '');
const byBare = new Map(data.map(e => [strip(e.emoji), e]));

/* ---------- Parse tags.txt ---------- */
const cats = new Map(), tagged = new Map(), errors = [];
readFileSync(join(ROOT, 'data/emoji/tags.txt'), 'utf8').split('\n').forEach((raw, i) => {
  const line = raw.trim();
  if (!line || line.startsWith('#')) return;
  if (line.startsWith('cat ')) {
    const [id, level, kind, label] = line.slice(4).split('|').map(s => s.trim());
    cats.set(id, { id, level: +level, kind, label, core: [], maybe: [] });
    return;
  }
  const [glyph, ...tags] = line.split(/\s+/);
  const e = byBare.get(strip(glyph));
  if (!e) { errors.push(`line ${i + 1}: ${glyph} is not in emojibase`); return; }
  if (e.version > MAX_VERSION) errors.push(`line ${i + 1}: ${glyph} ${e.label} is Emoji ${e.version}, newer than ${MAX_VERSION}`);
  if (tagged.has(e.emoji)) errors.push(`line ${i + 1}: ${glyph} is listed twice`);
  const entry = { core: [], maybe: [] };
  for (const t of tags) {
    const maybe = t.endsWith('?'), id = maybe ? t.slice(0, -1) : t;
    if (!cats.has(id)) { errors.push(`line ${i + 1}: unknown tag "${id}" on ${glyph}`); continue; }
    (maybe ? entry.maybe : entry.core).push(id);
    (maybe ? cats.get(id).maybe : cats.get(id).core).push(e.emoji);
  }
  tagged.set(e.emoji, entry);
});

/* A connection needs at least 4 sure members; under 6 it rarely survives the ambiguity check. */
const thin = [];
for (const c of cats.values()) {
  if (c.core.length < 4) errors.push(`cat ${c.id} has only ${c.core.length} sure members`);
  else if (c.core.length < 6) thin.push(`${c.id} (${c.core.length})`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

/* ---------- Full dataset ---------- */
const KIND_KEY = { noun: 'nouns', adjective: 'adjectives', descriptor: 'descriptors', wordplay: 'wordplay' };
const out = data
  .filter(e => e.version <= MAX_VERSION && e.group !== 2 && e.group !== 9)
  .map(e => {
    const row = {
      emoji: e.emoji, hexcode: e.hexcode, name: e.label, version: e.version,
      group: groupName[e.group] || null, subgroup: subgroupName[e.subgroup] || null,
      keywords: e.tags || []
    };
    const t = tagged.get(e.emoji);
    if (t) {
      row.tags = { nouns: [], adjectives: [], descriptors: [], wordplay: [] };
      for (const id of t.core) row.tags[KIND_KEY[cats.get(id).kind]].push(cats.get(id).label);
      if (t.maybe.length) row.tags.arguable = t.maybe.map(id => cats.get(id).label);
    }
    return row;
  });
writeFileSync(join(ROOT, 'data/emoji/emoji-tagged.json'), JSON.stringify({
  source: 'emojibase-data ' + JSON.parse(readFileSync(join(base, 'package.json'), 'utf8')).version + ' (MIT), Unicode CLDR annotations',
  connections: [...cats.values()].map(({ id, level, kind, label, core, maybe }) => ({ id, level, kind, label, members: core, arguable: maybe })),
  emoji: out
}, null, 1) + '\n');

/* ---------- Compact table for index.html ---------- */
const catLine = [...cats.values()].map(c => `${c.id}:${c.level}:${c.label}`).join('|');
const tagLines = [...tagged].map(([g, t]) => [g, ...t.core, ...t.maybe.map(x => x + '?')].join(' ')).join('\n');
const block = `/* EMOJI-TAGS:BEGIN generated by tools/build-emoji-data.mjs from data/emoji/tags.txt. Do not edit by hand. */
const EMOJI_CATS = ${JSON.stringify(catLine)};
const EMOJI_TAGS = \`
${tagLines}
\`;
/* EMOJI-TAGS:END */`;
const htmlPath = join(ROOT, 'index.html'), html = readFileSync(htmlPath, 'utf8');
const re = /\/\* EMOJI-TAGS:BEGIN[\s\S]*?EMOJI-TAGS:END \*\//;
if (!re.test(html)) { console.error('index.html has no EMOJI-TAGS block to replace'); process.exit(1); }
writeFileSync(htmlPath, html.replace(re, () => block));

console.log(`${tagged.size} emoji tagged across ${cats.size} connections; ${out.length} emoji in emoji-tagged.json.`);
if (thin.length) console.log(`Thin connections (used less often): ${thin.join(', ')}`);
